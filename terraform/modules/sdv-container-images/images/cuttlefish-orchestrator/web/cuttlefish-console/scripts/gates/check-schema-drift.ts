/**
 * Schema Drift Detection Script
 *
 * Compares the Zod schemas the Angular console actually parses responses with
 * against the OpenAPI spec generated by Huma in the Go backend. Both
 * directions fail the check:
 *  - a spec field no Zod schema accepts (backend data silently dropped)
 *  - a Zod field no spec field matches (dead frontend field that can never
 *    be populated)
 *
 * Five narrower tables ride along, covering what the response field-name
 * comparison cannot see: status enums, query-parameter names, response enums,
 * request-body patterns and request-body field names.
 *
 * Usage:
 *   go run ./tests/specgen &          # serves the spec on localhost:8888
 *   npm run check:schema-drift
 *   npx tsx scripts/check-schema-drift.ts [--api-url=http://localhost:8888]
 *
 * The only /v2 endpoints outside Huma (and therefore outside this check) are
 * the WebRTC signaling routes and the storage object up/download streams
 * (internal/router/router.go).
 */

