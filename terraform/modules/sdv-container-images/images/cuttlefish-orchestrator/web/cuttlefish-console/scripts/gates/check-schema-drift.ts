/**
 * Spec fields the console chooses not to consume. Removing an entry here
 * means wiring the field through the corresponding Zod schema and model.
 */
const UNCONSUMED_BY_DESIGN: Record<string, string[]> = {
  // cvd_id is an internal Host Orchestrator handle with no console surface.
  Device: ['cvd_id'],
  // boot_disk_type is provisioning knowledge, meaning which disk type a shape
  // must boot from, since C4 and N4 reject pd-*. The provisioner reads it; nothing
  // an operator picks depends on it.
  MachineType: ['boot_disk_type'],
  // The Autoscaler page is where a machine's pool is drawn. It groups the
  // canvas into a region per pool and reads the column off the fleet view. The
  // hosts page lists machines one by one and states no pool anywhere, so the
  // /v2 host entity's copy of the column feeds nothing; wire it through when
  // that page grows a surface for it.
  Host: ['pool'],
};

interface ZodLike {
  shape?: Record<string, unknown>;
  in?: ZodLike;
  unwrap?: () => ZodLike;
}

/** Walks pipe/optional wrappers to the input object and returns its keys. */
function zodInputKeys(schema: unknown): string[] {
  let cur = schema as ZodLike | undefined;
  for (let i = 0; cur && i < 10; i++) {
    if (cur.shape) {
      return Object.keys(cur.shape);
    }
    cur = cur.in ?? (typeof cur.unwrap === 'function' ? cur.unwrap() : undefined);
  }
  throw new Error('No object shape found on Zod schema');
}

async function fetchOpenAPISpec(apiUrl: string): Promise<OpenAPISpec> {
  const response = await fetch(`${apiUrl}/openapi.json`);
  if (!response.ok) {
    throw new Error(`Failed to fetch OpenAPI spec: ${response.status} ${response.statusText}`);
  }
  return response.json() as Promise<OpenAPISpec>;
}

function extractSchemaFields(
  schema: OpenAPISchema | undefined,
  schemas: Record<string, OpenAPISchema>
): string[] {
  if (!schema) {
    return [];
  }

  const fields: string[] = [];

  if (schema.$ref) {
    const refName = schema.$ref.replace('#/components/schemas/', '');
    return extractSchemaFields(schemas[refName], schemas);
  }

  if (schema.allOf) {
    for (const subSchema of schema.allOf) {
      fields.push(...extractSchemaFields(subSchema, schemas));
    }
  }

  if (schema.properties) {
    fields.push(...Object.keys(schema.properties));
  }

  return [...new Set(fields)];
}

/**
 * snake_case and camelCase spellings of the same field must match: the Zod
 * schemas list both variants while the wire uses one.
 */
function normalize(field: string): string {
  return field.toLowerCase().replaceAll('_', '');
}

interface Comparison {
  entity: string;
  missingInZod: string[];
  deadInZod: string[];
  skippedAllowlisted: string[];
}

function compareEntity(entity: string, specFields: string[], zodKeys: string[]): Comparison {
  const allowlist = new Set(UNCONSUMED_BY_DESIGN[entity] ?? []);
  // Huma injects a $schema link property; it is not part of the API contract.
  const spec = specFields.filter(f => f !== '$schema');
  const specNormalized = new Set(spec.map(normalize));
  const zodNormalized = new Set(zodKeys.map(normalize));

  return {
    entity,
    missingInZod: spec
      .filter(f => !allowlist.has(f))
      .filter(f => !zodNormalized.has(normalize(f)))
      .sort(),
    deadInZod: zodKeys.filter(k => !specNormalized.has(normalize(k))).sort(),
    skippedAllowlisted: spec.filter(f => allowlist.has(f)).sort(),
  };
}

const green = '\x1b[32m';
const red = '\x1b[31m';
const dim = '\x1b[2m';
const reset = '\x1b[0m';

function resolveApiUrl(args: string[]): string {
  const apiUrlArg = args.find(a => a.startsWith('--api-url='));
  return apiUrlArg ? apiUrlArg.split('=')[1] : 'http://localhost:8888';
}

/** Each check returns how many drifts it found; the counts add up to the verdict. */
function checkEntities(schemas: Record<string, OpenAPISchema>): number {
  let driftCount = 0;

  for (const [entity, zodSchema] of Object.entries(ENTITY_SCHEMAS)) {
    const openApiSchema = schemas[entity];
    if (!openApiSchema) {
      // An entity disappearing from the spec is itself drift.
      console.log(`${red}✗${reset} ${entity}: MISSING FROM SPEC`);
      driftCount++;
      continue;
    }

    const specFields = extractSchemaFields(openApiSchema, schemas);
    const result = compareEntity(entity, specFields, zodInputKeys(zodSchema));
    if (result.missingInZod.length > 0 || result.deadInZod.length > 0) {
      driftCount++;
      console.log(`${red}✗${reset} ${entity}: DRIFT`);
      if (result.missingInZod.length > 0) {
        console.log(`  Spec fields not accepted by Zod: ${result.missingInZod.join(', ')}`);
      }
      if (result.deadInZod.length > 0) {
        console.log(`  Zod fields matching no spec field: ${result.deadInZod.join(', ')}`);
      }
      continue;
    }

    const skipped =
      result.skippedAllowlisted.length > 0
        ? ` ${dim}(unconsumed on purpose: ${result.skippedAllowlisted.join(', ')})${reset}`
        : '';
    console.log(`${green}✓${reset} ${entity}: OK${skipped}`);
  }

  return driftCount;
}

function checkStatusEnums(spec: OpenAPISpec): number {
  let driftCount = 0;

  for (const check of STATUS_ENUMS) {
    const params = spec.paths?.[check.path]?.get?.parameters ?? [];
    const specEnum = params.find(p => p.name === check.param)?.schema?.enum;
    if (!specEnum) {
      console.log(
        `${red}✗${reset} ${check.label}: GET ${check.path} publishes no ${check.param} enum`
      );
      driftCount++;
      continue;
    }

    const consoleValues: readonly string[] = check.values;
    const missing = specEnum.filter(v => !consoleValues.includes(v)).sort();
    const bogus = consoleValues.filter(v => !specEnum.includes(v)).sort();
    if (missing.length === 0 && bogus.length === 0) {
      console.log(`${green}✓${reset} ${check.label}: enum OK (${specEnum.length} values)`);
      continue;
    }

    driftCount++;
    console.log(`${red}✗${reset} ${check.label}: ENUM DRIFT`);
    if (missing.length > 0) {
      console.log(`  Backend statuses missing in the console: ${missing.join(', ')}`);
    }
    if (bogus.length > 0) {
      console.log(`  Console statuses the backend never emits: ${bogus.join(', ')}`);
    }
  }

  return driftCount;
}

function checkQueryParams(spec: OpenAPISpec): number {
  let driftCount = 0;

  for (const check of QUERY_PARAMS) {
    const operation = spec.paths?.[check.path]?.get;
    if (!operation) {
      console.log(`${red}✗${reset} ${check.label}: the spec has no GET ${check.path}`);
      driftCount++;
      continue;
    }

    // Path parameters share the array; only the query half is comparable.
    const published = new Set(
      (operation.parameters ?? []).filter(p => p.in === 'query').map(p => p.name)
    );
    const consoleParams: readonly string[] = check.params;
    const unpublished = consoleParams.filter(p => !published.has(p)).sort();
    if (unpublished.length === 0) {
      console.log(`${green}✓${reset} ${check.label}: ${consoleParams.length} parameter(s) OK`);
      continue;
    }

    driftCount++;
    console.log(`${red}✗${reset} ${check.label}: PARAMETER DRIFT`);
    console.log(`  Sent by the console, absent from GET ${check.path}: ${unpublished.join(', ')}`);
  }

  return driftCount;
}

function checkResponseEnums(schemas: Record<string, OpenAPISchema>): number {
  let driftCount = 0;

  for (const check of RESPONSE_ENUMS) {
    const specEnum = schemas[check.schema]?.properties?.[check.field]?.enum;
    if (!specEnum) {
      console.log(
        `${red}✗${reset} ${check.label}: ${check.schema}.${check.field} publishes no enum`
      );
      driftCount++;
      continue;
    }

    const consoleValues: readonly string[] = check.values;
    const missing = specEnum.filter(v => !consoleValues.includes(v));
    const bogus = consoleValues.filter(v => !specEnum.includes(v));
    if (missing.length === 0 && bogus.length === 0) {
      console.log(`${green}✓${reset} ${check.label}: enum OK (${specEnum.length} values)`);
      continue;
    }

    driftCount++;
    console.log(`${red}✗${reset} ${check.label}: ENUM DRIFT`);
    if (missing.length > 0) {
      console.log(`  Backend values missing in the console: ${missing.join(', ')}`);
    }
    if (bogus.length > 0) {
      console.log(`  Console values the backend never emits: ${bogus.join(', ')}`);
    }
  }

  return driftCount;
}

function checkRequestPatterns(schemas: Record<string, OpenAPISchema>): number {
  let driftCount = 0;

  for (const check of REQUEST_PATTERNS) {
    const specPattern = schemas[check.schema]?.properties?.[check.field]?.pattern;
    if (!specPattern) {
      console.log(
        `${red}✗${reset} ${check.label}: ${check.schema}.${check.field} publishes no pattern`
      );
      driftCount++;
      continue;
    }

    if (specPattern === check.regex.source) {
      console.log(`${green}✓${reset} ${check.label}: pattern OK (${specPattern})`);
      continue;
    }

    driftCount++;
    console.log(`${red}✗${reset} ${check.label}: PATTERN DRIFT`);
    console.log(`  Spec:    ${specPattern}`);
    console.log(`  Console: ${check.regex.source}`);
  }

  return driftCount;
}

function checkRequestFields(schemas: Record<string, OpenAPISchema>): number {
  let driftCount = 0;

  for (const check of REQUEST_FIELDS) {
    const schema = schemas[check.schema];
    if (!schema) {
      console.log(`${red}✗${reset} ${check.label}: the spec has no ${check.schema} schema`);
      driftCount++;
      continue;
    }

    const published = new Set(Object.keys(schema.properties ?? {}));
    const consoleFields: readonly string[] = check.fields;
    const undeclared = consoleFields.filter(f => !published.has(f)).sort();
    if (undeclared.length === 0) {
      console.log(`${green}✓${reset} ${check.label}: ${consoleFields.length} field(s) OK`);
      continue;
    }

    driftCount++;
    console.log(`${red}✗${reset} ${check.label}: REQUEST FIELD DRIFT`);
    console.log(`  Sent by the console, absent from ${check.schema}: ${undeclared.join(', ')}`);
  }

  return driftCount;
}

function reportSummary(driftCount: number): never {
  console.log('\nSummary');
  console.log('-------');
  if (driftCount === 0) {
    console.log(
      `${green}✓ All ${Object.keys(ENTITY_SCHEMAS).length} schemas in sync with backend${reset}`
    );
    process.exit(0);
  }
  console.log(`${red}✗ ${driftCount} schema(s) drifted${reset}`);
  console.log('\nTo fix: update the corresponding *.schema.ts (or, for a field the');
  console.log('console will not consume, add it to UNCONSUMED_BY_DESIGN in this script).');
  process.exit(1);
}

async function main(): Promise<void> {
  const apiUrl = resolveApiUrl(process.argv.slice(2));

  console.log('Schema Drift Detection');
  console.log('======================\n');
  console.log(`Fetching OpenAPI spec from: ${apiUrl}/openapi.json\n`);

  let spec: OpenAPISpec;
  try {
    spec = await fetchOpenAPISpec(apiUrl);
  } catch (error) {
    console.error('Error fetching OpenAPI spec:');
    console.error((error as Error).message);
    console.log('\nMake sure the spec server is running: go run ./tests/specgen &');
    process.exit(1);
  }

  console.log(`OpenAPI Version: ${spec.openapi}`);
  console.log(`API: ${spec.info.title} v${spec.info.version}\n`);

  const schemas = spec.components?.schemas ?? {};

  // Left-to-right evaluation is what keeps the six sections reporting in order.
  const driftCount =
    checkEntities(schemas) +
    checkStatusEnums(spec) +
    checkQueryParams(spec) +
    checkResponseEnums(schemas) +
    checkRequestPatterns(schemas) +
    checkRequestFields(schemas);

  reportSummary(driftCount);
}

main().catch(error => {
  console.error(error);
  process.exit(1);
});
